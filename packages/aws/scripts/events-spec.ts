/**
 * The provider spec for the event models convert.ts writes from the
 * EventBridge `aws.events` schema registry (`<service>-events`).
 *
 * An event model has no operations: each `<DetailType>Event` envelope,
 * tagged with {@link AWS_EVENT_TRAIT}, is a root. The module is types only,
 * like GitHub's webhook payloads, and closes with an `Events` map from
 * detail-type to envelope, and `Event`, their union narrowed by
 * `detail-type` — what an EventBridge rule's target receives.
 */
import type { SdkSpec } from "@distilled.cloud/dev/codegen/generator";

/** Marks an event envelope with its `source` and `detail-type`. */
export const AWS_EVENT_TRAIT = "com.distilled.aws#event";

const NULLABLE_TRAIT = "com.distilled.openapi#nullable";

export const isEventsModel = (model: { shapes?: Record<string, any> }): boolean =>
  Object.values(model.shapes ?? {}).some((shape) => shape?.traits?.[AWS_EVENT_TRAIT]);

/** `com.amazonaws.ses.events#EmailBouncedEvent` → `ses-events`. */
export const eventsResourceName = (model: { shapes?: Record<string, any> }): string => {
  const id = Object.keys(model.shapes ?? {})[0] ?? "";
  const service = /^com\.amazonaws\.(.+)\.events#/.exec(id)?.[1];
  if (service === undefined) throw new Error(`not an event model: ${id}`);
  return `${service}-events`;
};

export const eventsSpec = (model: { shapes: Record<string, any> }): SdkSpec => {
  const events: Array<{ detailType: string; name: string }> = [];
  for (const [id, shape] of Object.entries<any>(model.shapes)) {
    const meta = shape.traits?.[AWS_EVENT_TRAIT];
    if (!meta) continue;
    events.push({ detailType: meta.detailType, name: id.slice(id.indexOf("#") + 1) });
  }
  events.sort((a, b) => a.detailType.localeCompare(b.detailType));
  const map = [
    "",
    "/** Every event this service sends to EventBridge, keyed by its `detail-type`. */",
    "export interface Events {",
    ...events.map(({ detailType, name }) => `  ${JSON.stringify(detailType)}: ${name};`),
    "}",
    "",
    "/** An event's `detail-type`. */",
    "export type DetailType = keyof Events;",
    "",
    "/** Any event this service sends, narrowed by its `detail-type`. */",
    'export type Event = { [K in DetailType]: Events[K] & { "detail-type": K } }[DetailType];',
    "",
  ].join("\n");
  return {
    nullableTrait: NULLABLE_TRAIT,
    sourceNote: ".generated-specs (specs/spec-mirror-aws event-schemas)",
    extraRoots: () => events.map(({ name }) => `${eventsNamespace(model)}#${name}`),
    // No operations, so no protocol, errors or retry to import. The schema
    // consts nothing uses are dropped after generation, leaving the types.
    header: () =>
      "// AUTO-GENERATED by scripts/generate.ts from .generated-specs (specs/spec-mirror-aws event-schemas). Do not edit.\n" +
      'import * as S from "@distilled.cloud/core/schema-lite";\n\n',
    postProcess: (code) => code + map,
  };
};

const eventsNamespace = (model: { shapes: Record<string, any> }): string => {
  const id = Object.keys(model.shapes)[0] ?? "";
  return id.slice(0, id.indexOf("#"));
};
