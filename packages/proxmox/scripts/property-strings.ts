import { namedPropertyFormats } from "./property-formats.ts";
import { FORMAT, type Model } from "./schema.ts";

/** The fields of a format that the wire codec reads. Server-side validation stays authoritative. */
const CODEC_FIELDS = new Set(["type", "optional", "default_key", "alias", "keyAlias", "enum"]);

const isObject = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

/**
 * `src/property-strings.ts`: a codec for every property-string member, per area and shape, so
 * operation-specific differences in a format are kept.
 */
export function generatePropertyStrings(models: ReadonlyMap<string, Model>): string {
  const lines = [
    "// AUTO-GENERATED by scripts/generate.ts from .generated-specs. Do not edit.",
    'import { propertyString } from "./property-string.ts";',
  ];
  for (const [area, model] of models) {
    lines.push(`export const ${area} = {`);
    for (const [id, shape] of Object.entries(model.shapes)) {
      const codecs = Object.entries(shape.members ?? {}).flatMap(([key, member]) => {
        const trait = member.traits?.[FORMAT];
        const format = typeof trait === "string" ? namedPropertyFormats[trait] : trait;
        if (!isObject(format)) return [];
        const fields = Object.fromEntries(
          Object.entries(format).map(([name, field]) => [
            name,
            isObject(field)
              ? Object.fromEntries(Object.entries(field).filter(([k]) => CODEC_FIELDS.has(k)))
              : {},
          ]),
        );
        return [`${JSON.stringify(key)}: /*@__PURE__*/ propertyString(${JSON.stringify(fields)}),`];
      });
      if (codecs.length) lines.push(`${JSON.stringify(id.split("#")[1])}: {`, ...codecs, "},");
    }
    lines.push("};");
  }
  return lines.join("\n") + "\n";
}
