import { readFile, writeFile } from "node:fs/promises";
import type { PatchFile } from "@distilled.cloud/core/json-patch";

/**
 * Both PUT endpoints use the same multipart metadata. Keep the ordinary
 * Worker patch authoritative, including its typed nested shapes and wire
 * names, and specialize only the Smithy namespace / operation prefix.
 * Endpoint-specific additions belong in separate patches, not this output.
 *
 * Wire format reference:
 * https://github.com/cloudflare/workers-sdk/blob/main/packages/deploy-helpers/src/deploy/helpers/create-worker-upload-form.ts
 * https://github.com/cloudflare/workers-sdk/blob/main/packages/workers-utils/src/types.ts
 */
export const dispatchUploadPatch = (source: PatchFile): PatchFile => ({
  description:
    "Generated by scripts/sync-worker-upload-patches.ts from workers/putScript.manual.json. Edit the source patch for shared upload metadata; do not edit this file. Both PUT endpoints use the same multipart metadata, including assets.config._headers and assets.config._redirects.",
  patches: source.patches
    .filter((patch) =>
      patch.path.startsWith("/shapes/com.cloudflare.workers#PutScript"),
    )
    .map((patch) =>
      JSON.parse(
        JSON.stringify(patch).replaceAll(
          "com.cloudflare.workers#PutScript",
          "com.cloudflare.workers_for_platforms#PutDispatchNamespaceScript",
        ),
      ),
    ),
});

export const syncWorkerUploadPatches = async () => {
  const patches = new URL("../patches/", import.meta.url);
  const source: PatchFile = JSON.parse(
    await readFile(new URL("workers/putScript.manual.json", patches), "utf8"),
  );
  await writeFile(
    new URL(
      "workers_for_platforms/putDispatchNamespaceScript.manual.json",
      patches,
    ),
    `${JSON.stringify(dispatchUploadPatch(source), null, 2)}\n`,
  );
};

if (import.meta.main) await syncWorkerUploadPatches();
