/**
 * Generates `src/regional-endpoints.ts` from the discovery documents'
 * `endpoints[]` (regional `*.{location}.rep.googleapis.com` hosts and
 * locational `{location}-*.googleapis.com` hosts).
 *
 *   bun scripts/regional-endpoints.ts
 */
import * as fs from "node:fs";
import * as path from "node:path";

interface DiscoveryEndpoint {
  endpointUrl: string;
  location: string;
}

const root = path.resolve(import.meta.dir, "..");
const specsDir = path.join(root, "specs/spec-mirror-gcp/specs");

/** Global base URL → per-location host template → locations served. */
const table = new Map<string, Map<string, Set<string>>>();

for (const file of fs.readdirSync(specsDir).sort()) {
  if (!file.endsWith(".json") || file.startsWith("_")) continue;
  const doc = JSON.parse(fs.readFileSync(path.join(specsDir, file), "utf8"));
  if (typeof doc !== "object" || !Array.isArray(doc.endpoints)) continue;
  const baseUrl = `${doc.rootUrl}${doc.servicePath ?? ""}`;
  const servicePath: string = doc.servicePath ?? "";
  for (const endpoint of doc.endpoints as DiscoveryEndpoint[]) {
    if (!endpoint.endpointUrl.includes(endpoint.location)) continue;
    const template =
      endpoint.endpointUrl.replace(endpoint.location, "{location}") +
      servicePath;
    // Prefer `.rep.googleapis.com` (regional) over locational hosts: Google
    // recommends regional endpoints and they enforce data residency.
    const byTemplate = table.get(baseUrl) ?? new Map<string, Set<string>>();
    const locations = byTemplate.get(template) ?? new Set<string>();
    locations.add(endpoint.location);
    byTemplate.set(template, locations);
    table.set(baseUrl, byTemplate);
  }
}

const entries = [...table.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([baseUrl, byTemplate]) => {
    const templates = [...byTemplate.entries()].sort(([left], [right]) => {
      const rank = (t: string) => (t.includes(".rep.googleapis.com") ? 0 : 1);
      return rank(left) - rank(right) || left.localeCompare(right);
    });
    // Datastore also publishes `batch-datastore.*` hosts; keep only hosts
    // for this service's own name.
    const service = new URL(baseUrl).host.split(".")[0]!;
    const own = templates.filter(([t]) => {
      const host = new URL(t.replace("{location}", "x")).host;
      return host.startsWith(`${service}.`) || host.startsWith(`x-${service}.`);
    });
    const body = (own.length ? own : templates)
      .map(
        ([template, locations]) =>
          `    { template: ${JSON.stringify(template)}, locations: ${JSON.stringify([...locations].sort())} },`,
      )
      .join("\n");
    return `  ${JSON.stringify(baseUrl)}: [\n${body}\n  ],`;
  });

const out = `// Generated by scripts/regional-endpoints.ts from the Google discovery
// documents' \`endpoints[]\`. Do not edit.

/**
 * Regional hosts per service, keyed by the service's global base URL, in
 * preference order (\`*.rep.googleapis.com\` first). \`template\` has a
 * \`{location}\` placeholder; \`locations\` are the ones Google publishes a
 * host for.
 */
export const REGIONAL_ENDPOINTS: Readonly<
  Record<
    string,
    ReadonlyArray<{ readonly template: string; readonly locations: ReadonlyArray<string> }>
  >
> = {
${entries.join("\n")}
};
`;
fs.writeFileSync(path.join(root, "src/regional-endpoints.ts"), out);
console.log(`wrote ${entries.length} services`);
