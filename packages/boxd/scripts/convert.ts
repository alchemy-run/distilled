#!/usr/bin/env -S node --conditions=bun
/**
 * convert — turn boxd's proto3 gRPC API into a Smithy 2.0 JSON model.
 *
 * Input:  specs/spec-mirror-boxd/specs/api.proto
 *         (a 24h mirror of boxd-sh/sdk/proto/api.proto)
 * Output: .generated-specs/boxd.json  (one Smithy model for `service BoxdApi`)
 *         src/descriptors.ts          (the binary wire codec's table)
 *
 * The proto→Smithy converter lives in `@distilled.cloud/dev/codegen/proto`.
 * Operations are unary gRPC methods, stamped as
 * `POST /boxd.api.v1.BoxdApi/<Method>` with proto3 JSON field names.
 * Server-streaming RPCs are kept as operations that collect the stream
 * (`{ items }`); client- and bidi-streaming RPCs (`Exec`, `UploadFileStream`,
 * `FsWrite`, `DesktopTunnel`) are skipped.
 *
 * boxd's API speaks binary gRPC, and gRPC-Web over HTTP/1.1. The model
 * describes the proto3 JSON shape; `src/descriptors.ts` lets the protocol
 * transcode it to protobuf on the wire.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { clearModels, writeModel } from "@distilled.cloud/dev/codegen/models";
import { finalizeConvert } from "@distilled.cloud/dev/codegen/patches";
import {
  assertDescriptorsCover,
  convertProtoToSmithy,
  parseProto,
  protoDescriptors,
} from "@distilled.cloud/dev/codegen/proto";
import { resolveSpecPath } from "@distilled.cloud/dev/codegen/spec-path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT_DIR = path.join(ROOT, ".generated-specs");

const specPath = resolveSpecPath(ROOT, "specs/spec-mirror-boxd/specs/api.proto");
if (!fs.existsSync(specPath)) {
  throw new Error(
    `${specPath} not found — run \`pnpm specs:local boxd\` (or \`pnpm run specs:fetch\` once the mirror exists)`,
  );
}
const files = [parseProto(fs.readFileSync(specPath, "utf-8"), "api.proto")];

clearModels(OUT_DIR);

const result = convertProtoToSmithy({
  files,
  namespace: "com.boxd",
  serviceName: "Boxd",
  serviceTitle: "boxd",
  serviceDocumentation:
    "boxd.api.v1.BoxdApi. Each operation is POST /boxd.api.v1.BoxdApi/<Method> with a proto3 JSON body.",
  protoService: "boxd.api.v1.BoxdApi",
  skipStreaming: true,
  collectServerStreams: true,
  skipDeprecated: true,
});
writeModel(path.join(OUT_DIR, "boxd.json"), result.model);
console.log(
  `✅ boxd: ${result.converted} ops, ${result.skippedStreaming} streaming skipped, ` +
    `${result.skippedDeprecated} deprecated skipped, ${result.shapeCount} shapes → ${OUT_DIR}`,
);

/** A string literal the formatter leaves alone (single quotes unless escaping). */
const quoteForSource = (text: string): string =>
  /['\\\n]/.test(text) ? JSON.stringify(text) : `'${text}'`;

// Binary wire descriptors for the gRPC protocol (src/protocol.ts): the
// proto3 JSON bodies the services build are transcoded with this table.
const descriptors = protoDescriptors(files, { collectServerStreams: true, skipDeprecated: true });
assertDescriptorsCover([result.model], descriptors);
fs.writeFileSync(
  path.join(ROOT, "src", "descriptors.ts"),
  [
    "// AUTO-GENERATED by scripts/convert.ts from boxd's api.proto. Do not edit.",
    'import type { ProtoDescriptors } from "@distilled.cloud/core/protobuf";',
    "",
    "/** Field numbers, kinds, enums and gRPC methods for the binary wire codec. */",
    "export const descriptors: ProtoDescriptors = /*@__PURE__*/ JSON.parse(",
    `  ${quoteForSource(JSON.stringify(descriptors))},`,
    ");",
    "",
  ].join("\n"),
);
console.log(
  `   descriptors: ${Object.keys(descriptors.messages).length} messages, ${Object.keys(descriptors.methods).length} methods`,
);

// One model: its patches sit at the root of patches/. boxd names its RPCs
// verb first already (`CreateVm`); the `Fs*` family (`FsList`, `FsStat`)
// keeps its prefix, as the official SDKs' `fs.list` does.
await finalizeConvert({ root: ROOT, patchesFor: () => "", operationNaming: "as-is" });
